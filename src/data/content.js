export function buildWhatsAppUrl({ name, service, eventDate, location, guests, sareeCount, message }) {
  const lines = [
    `*Hi Raje AR / Trichy_AR Makeup Artists!*`,
    `I found your website and would like to check date availability & book a service:`,
    ``,
    `👤 *Name:* ${name || "Not specified"}`,
    `💄 *Service:* ${service || "HD Bridal Muhurtham"}`,
    `📅 *Event Date:* ${eventDate || "To be confirmed"}`,
    `📍 *Location / Mandapam:* ${location || "Trichy / Manachanallur"}`,
    guests ? `👥 *Family / Guest Count:* ${guests}` : null,
    sareeCount ? `🥻 *Saree Pre-Pleating Count:* ${sareeCount}` : null,
    message ? `💬 *Additional Note:* ${message}` : null,
    ``,
    `Please share your availability and final quote. Looking forward to your reply! ✨`
  ].filter(Boolean);

  const text = encodeURIComponent(lines.join("\n"));
  return `https://wa.me/${BUSINESS_INFO.whatsappNumber}?text=${text}`;
}
